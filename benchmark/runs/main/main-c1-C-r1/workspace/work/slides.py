def nav(id_, role, sec=None):
    s = {"id": id_, "role": role, "status": "filled"}
    if sec:
        s["section_id"] = sec
    if role == "agenda_tracker":
        s.update({"archetype": "agenda-tracker", "message_type": "navigation"})
    return s


def C(id_, sec, title, archetype, mtype, body, **kw):
    s = {"id": id_, "role": "content", "section_id": sec, "status": "filled",
         "lead_message": {"text": title}, "message_type": mtype, "archetype": archetype, "body": body}
    lm = kw.pop("lm", {})
    s["lead_message"].update(lm)
    s.update(kw)
    return s


def B(id_, sec, title, archetype, body, backup_of=None, **kw):
    s = {"id": id_, "role": "backup", "section_id": sec, "status": "filled",
         "lead_message": {"prefix": "BACKUP:", "text": title}, "message_type": "item", "archetype": archetype, "body": body}
    if backup_of:
        s["backup_of"] = backup_of
    lm = kw.pop("lm", {})
    s["lead_message"].update(lm)
    s.update(kw)
    return s


